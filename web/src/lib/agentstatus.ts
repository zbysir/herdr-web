/**
 * agent 状态那几个档的**颜色和排序，只有一份**。
 *
 * 取值来自 herdr 的 `agent_status`（实测就这四个：`blocked` / `working` / `done` / `idle`），
 * 认不出的一律当「没有状态」处理 —— 那是别人的字段，会加档。
 *
 * # 为什么抽出来
 *
 * 现在有两处要画它：面板一览那一列点（`components/PaneSwitcher.tsx`）和 chat 模式头上那个
 * 状态（`components/ChatPanel.tsx`）。两份平行的色表迟早对不上，而「同一个状态在两块界面上
 * 是两个颜色」这种毛病没人会当 bug 报，只会让人慢慢不信这些颜色。
 *
 * # 为什么**词**不在这儿
 *
 * 各处的说法是刻意不一样的：面板一览那一行只有几十像素宽，所以是「等你」「完成」这种最短的
 * 写法，而且**只给最该被看见的两个加字**（其余靠点的颜色，不然每行都塞满标签）；chat 模式
 * 头上那一条有整行宽度，要说的是「在等你回答（回终端）」这种能指路的话。硬统一成一套词的
 * 结果是两边都别扭 —— 所以这儿只管颜色和排序这两件**必须一致**的事。
 */

/**
 * 状态点的颜色：**红 = 等你，绿 = 跑完了，黄 = 在跑**，闲着是灰点。
 *
 * 「在跑」用黄不用绿 —— 和 herdr 自己 agents 栏里那个黄点一致。绿留给「跑完了」（这是
 * 通用约定，一眼就知道是好事）。只有闲着没有颜色：一列点里要是全是彩的，就没有重点了。
 */
export const STATUS_DOT: Record<string, string> = {
  working: 'bg-warn',
  blocked: 'bg-bad',
  done: 'bg-ok',
  idle: 'bg-muted',
}

/**
 * 排序用的桶：需要人看的 > 完成的 > 在跑的 > 闲着的，非 agent pane 永远最后。
 *
 * 前两档是需求方定的（需要人看的 > 完成的）。「在跑」单独一档也是他定的 —— 一开始
 * 「在跑」和「闲着」合成一档，理由是两个都不需要你、谁在前面没有客观答案；实际用起来
 * 不对：黄点那个（正在跑）会被十几个闲着的埋掉，而列表里最想一眼看到的就是它。
 */
export const STATUS_BUCKET: Record<string, number> = { blocked: 0, done: 1, working: 2, idle: 3 }
